def card_en(s: str) -> str:
    out = []
    for part in s.split("，"):
        for zh, en in CARD_PREFIX:
            if part.startswith(zh):
                out.append(en + part[len(zh):])
                break
        else:
            out.append(part)
    return ", ".join(out)


def add_cards() -> None:
    import re
    text = (ROOT / "scripts" / "weapons" / "weapon_data.gd").read_text(encoding="utf-8")
    for m in re.finditer(r'"card": "([^"]+)"', text):
        EN[m.group(1)] = card_en(m.group(1))
    EN["弹射 1 次，穿透保持 5"] = "1 bounce, pierce stays 5"


